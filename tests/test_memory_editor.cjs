'use strict';
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const assert=require('node:assert/strict');
const source=fs.readFileSync(path.join(__dirname,'../manager_app/static/app.js'),'utf8');
const prefix=source.split(/\r?\n/).filter(line=>line.startsWith('const esc=')||line.startsWith('function pill(')||line.startsWith('function button(')).join('\n');
const helpers=source.slice(source.indexOf('const memoryFields='),source.indexOf('function friendPanel('));
const context=vm.createContext({FormData:class{constructor(form){this.values=form.values;}get(name){return this.values[name]??null;}}});
vm.runInContext(prefix+'\n'+helpers+'\nglobalThis.memoryUI={memoryCard,memoryEditor,memoryEditPayload};',context);
const profile={id:'fixture-user',nickname:'<测试用户>',facts:{兴趣:'</textarea><script>bad()</script>'},revision:'a'.repeat(64),enabled:true};
const editor=context.memoryUI.memoryEditor(profile);
assert.equal((editor.match(/<textarea /g)||[]).length,6);
assert.equal((editor.match(/maxlength="240"/g)||[]).length,6);
assert(!editor.includes('<script>'));
assert(editor.includes('&lt;/textarea&gt;'));
assert(/<button\b(?=[^>]*data-action="memory-edit-cancel")(?=[^>]*type="button")[^>]*>/.test(editor));
assert(context.memoryUI.memoryCard({...profile,enabled:false}).includes(' disabled'));
const payload=context.memoryUI.memoryEditPayload({dataset:{user:profile.id,revision:profile.revision},values:{兴趣:'新的测试资料'}});
assert.equal(payload.user,profile.id);assert.equal(payload.revision,profile.revision);
assert.equal(Object.keys(payload.facts).length,6);assert.equal(payload.facts.兴趣,'新的测试资料');assert.equal(payload.facts.称呼,'');
console.log('Memory editor rendering, escaping and payload checks passed.');
